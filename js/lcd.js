/** Decode le paquet rendu par Sim.lcd(). */
export function parseLcd(v) {
  if (!v || v.length < 151) return null;
  return {
    chars: v.subarray(0, 80), cgram: v.subarray(80, 144),
    on: v[144], cursor: v[145], blink: v[146], init: v[147], twoLines: v[148],
    curRow: v[149], curCol: v[150], version: v[151] | (v[152] << 8) | (v[153] << 16) | (v[154] << 24),
    absent: v[155],
  };
}

/** Texte lisible du LCD (pour les infobulles et l'accessibilite). */
export function lcdText(st) {
  if (!st) return '';
  const rows = [];
  for (let r = 0; r < 4; r++) {
    let s = '';
    for (let c = 0; c < 20; c++) {
      const ch = st.chars[r * 20 + c];
      s += ch >= 0x20 && ch < 0x7F ? (ch === 0x5C ? '¥' : String.fromCharCode(ch)) : ch === 4 ? '\\' : '·';
    }
    rows.push(s);
  }
  return rows.join('\n');
}

/**
 * Dessine le LCD dans le rectangle (x, y, w, h) du contexte g.
 * st : etat (parseLcd) ou null ; contrast : 0..1 ; powered ; t : temps (ms) pour le clignotement.
 */
export function drawLcd(g, x, y, w, h, st, contrast, powered, t) {
  // fond : retroeclairage vert-jaune (eteint hors tension)
  const lit = powered && !(st && st.absent);
  const grd = g.createLinearGradient(x, y, x, y + h);
  if (lit) { grd.addColorStop(0, '#b9d84a'); grd.addColorStop(1, '#93b52c'); }
  else { grd.addColorStop(0, '#4a5530'); grd.addColorStop(1, '#3a4426'); }
  g.fillStyle = grd;
  g.fillRect(x, y, w, h);
  const padX = w * 0.03, padY = h * 0.07;
  const cw = (w - 2 * padX) / (20 * 6 - 1);     // pas d'un point
  const ch = (h - 2 * padY) / (4 * 9 - 1);
  const p = Math.min(cw, ch);
  const dot = p * 0.86;
  const ox = x + (w - p * (20 * 6 - 1)) / 2, oy = y + (h - p * (4 * 9 - 1)) / 2;
  const c = Math.max(0, Math.min(1, contrast));
  const onA = powered ? Math.max(0, Math.min(1, (c - 0.18) / 0.45)) : 0;
  const offA = powered ? Math.max(0, (c - 0.78) / 0.22) * 0.55 + 0.05 : 0.03;
  const blinkOn = Math.floor(t / 400) % 2 === 0;
  for (let r = 0; r < 4; r++) {
    for (let col = 0; col < 20; col++) {
      let rows = null;
      let full = false;
      if (powered && st && !st.absent) {
        if (!st.init) full = (r === 0 || r === 2);           // ecran de mise sous tension (1 ligne)
        else if (st.on) {
          const code = st.chars[r * 20 + col];
          rows = code < 16 ? st.cgram.subarray((code & 7) * 8, (code & 7) * 8 + 8) : GLYPHS.subarray(code * 8, code * 8 + 8);
        }
      }
      const cx0 = ox + col * 6 * p, cy0 = oy + r * 9 * p;
      const isCur = st && st.on && st.init && st.curRow === r && st.curCol === col;
      for (let yy = 0; yy < 8; yy++) {
        let bits = full ? 0x1F : rows ? rows[yy] & 0x1F : 0;
        if (isCur && st.cursor && yy === 7) bits = 0x1F;
        if (isCur && st.blink && blinkOn) bits = 0x1F;
        for (let xx = 0; xx < 5; xx++) {
          const on = (bits >> (4 - xx)) & 1;
          const a = on ? onA : offA;
          if (a <= 0.01) continue;
          g.fillStyle = `rgba(22,36,8,${a.toFixed(3)})`;
          g.fillRect(cx0 + xx * p, cy0 + yy * p, dot, dot);
        }
      }
    }
  }
  if (lit) {
    // reflet
    const gl = g.createLinearGradient(x, y, x, y + h * 0.5);
    gl.addColorStop(0, 'rgba(255,255,255,0.10)'); gl.addColorStop(1, 'rgba(255,255,255,0)');
    g.fillStyle = gl; g.fillRect(x, y, w, h * 0.5);
  }
}

export class LcdView {
  constructor(canvas) {
    this.cv = canvas;
    this.g = canvas.getContext('2d');
    this.resize();
  }
  resize() {
    const r = this.cv.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    this.cv.width = Math.round((r.width || 448) * dpr);
    this.cv.height = Math.round((r.height || 120) * dpr);
  }
  draw(st, contrast, powered, t) {
    drawLcd(this.g, 0, 0, this.cv.width, this.cv.height, st, contrast, powered, t);
  }
}
