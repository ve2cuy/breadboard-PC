// Glyphes : 256 x 8 rangees de 5 bits (bit 4 = colonne de gauche)
const GLYPHS = new Uint8Array(256 * 8);
function putCols(code, cols) {
  for (let r = 0; r < 8; r++) {
    let v = 0;
    for (let c = 0; c < 5; c++) if ((cols[c] >> r) & 1) v |= 1 << (4 - c);
    GLYPHS[code * 8 + r] = v;
  }
}
for (let i = 0; i < 96; i++) putCols(0x20 + i, ASCII.slice(i * 5, i * 5 + 5));
for (const [k, v] of Object.entries(UPPER)) putCols(+k, v);

// Katakana demi-chasse (A1h-DEh) : traces depuis la police du systeme, reduits a 5x8
function rasterKatakana() {
  try {
    const W = 50, H = 80;
    const cv = document.createElement('canvas');
    cv.width = W; cv.height = H;
    const g = cv.getContext('2d', { willReadFrequently: true });
    for (let code = 0xA1; code <= 0xDE; code++) {
      if (UPPER[code]) continue;
      const ch = String.fromCharCode(0xFF61 + (code - 0xA1));
      g.fillStyle = '#000'; g.fillRect(0, 0, W, H);
      g.fillStyle = '#fff';
      g.font = 'bold 76px "MS Gothic", "Yu Gothic", "Noto Sans JP", sans-serif';
      g.textAlign = 'center'; g.textBaseline = 'alphabetic';
      g.fillText(ch, W / 2, 68);
      const d = g.getImageData(0, 0, W, H).data;
      for (let r = 0; r < 8; r++) {
        let v = 0;
        for (let c = 0; c < 5; c++) {
          let s = 0;
          for (let y = r * 10; y < r * 10 + 10; y++) for (let x = c * 10; x < c * 10 + 10; x++) s += d[(y * W + x) * 4];
          if (s / 100 / 255 > 0.3) v |= 1 << (4 - c);
        }
        GLYPHS[code * 8 + r] = v;
      }
    }
  } catch (e) { /* sans canevas : katakana vides */ }
}
rasterKatakana();

