print('CLAVIER_NB_CODES equ %d' % N)
table('clavier_normal', 0, 'sans Maj')
table('clavier_maj', 1, 'avec Maj')
table('clavier_xt', None, 'code XT (jeu 1) rendu dans AH par INT 16h ; 0 = touche ignoree')
